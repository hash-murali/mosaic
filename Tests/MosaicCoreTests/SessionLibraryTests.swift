@testable import MosaicCore

@Test func duplicateSourcesReusePendingAndApprovedRecordsButNotMatchingText() {
    var library = SessionLibrary()
    let first = Record(observation: .init(text: "Synthetic train"))
    let duplicate = Record(observation: first.observation)
    #expect(library.add(first, sourceFingerprint: "synthetic-source-A") == first.id)
    let draft = ReviewDraft(text: "Synthetic ferry", usesCorrection: true)
    library.updateDraft(draft, for: first.id)
    #expect(library.add(duplicate, sourceFingerprint: "synthetic-source-A") == first.id)
    #expect(library.pending.count == 1)
    #expect(library.draft(for: first.id) == draft)
    library.approveDraft(for: first.id)
    #expect(library.add(duplicate, sourceFingerprint: "synthetic-source-A") == first.id)
    #expect(library.search("ferry").count == 1)
    #expect(library.pending.isEmpty)
    #expect(library.add(duplicate, sourceFingerprint: "synthetic-source-B") == duplicate.id)
    #expect(library.records.count == 2)
    library.discard(first.id)
    #expect(library.record(forSourceFingerprint: "synthetic-source-A") == nil)
    #expect(library.add(first, sourceFingerprint: "synthetic-source-A") == first.id)
    #expect(library.draft(for: first.id)?.usesCorrection == false)
}

@Test func newImportsPreserveApprovedRecordsAndPendingReviews() {
    var library = SessionLibrary()
    let first = Record(observation: .init(text: "Synthetic train 1900"))
    let second = Record(observation: .init(text: "Synthetic ferry 2100"))
    let third = Record(observation: .init(text: "Synthetic cafe 0800"))
    library.add(first)
    library.review(first.id)
    library.add(second)
    library.add(third)
    #expect(library.search("train").map(\.id) == [first.id])
    #expect(library.search("ferry").isEmpty)
    #expect(library.pending.map(\.id) == [second.id, third.id])
    library.review(second.id, correction: .init(text: "Synthetic ferry 2200"))
    #expect(library.search("2200").map(\.id) == [second.id])
    #expect(library.search("2100").isEmpty)
    #expect(library.records[1].observation == second.observation)
    library.discard(third.id)
    #expect(library.pending.isEmpty)
    #expect(library.search("train").map(\.id) == [first.id])
    #expect(library.search("ferry").map(\.id) == [second.id])
}

@Test func pendingDraftsSurviveOtherImportsAndStayOutOfSearch() {
    var library = SessionLibrary()
    let first = Record(observation: .init(text: "Synthetic train 1900"))
    let second = Record(observation: .init(text: "Synthetic ferry 2100"))
    library.add(first)
    let edit = ReviewDraft(text: "Synthetic train 2000", usesCorrection: true)
    library.updateDraft(edit, for: first.id)
    library.add(second)
    library.updateDraft(.init(text: "Synthetic ferry 2200"), for: second.id)
    #expect(library.draft(for: first.id) == edit)
    #expect(library.draft(for: second.id)?.usesCorrection == false)
    #expect(library.search("2000").isEmpty)
    #expect(library.records[0].observation == first.observation)
    library.approveDraft(for: first.id)
    #expect(library.search("2000").map(\.id) == [first.id])
    #expect(library.search("1900").isEmpty)
    #expect(library.draft(for: first.id) == nil)
    library.updateDraft(.init(text: "Must not replace approved text", usesCorrection: true), for: first.id)
    library.approveDraft(for: first.id)
    #expect(library.search("2000").map(\.id) == [first.id])
    library.approveDraft(for: second.id)
    #expect(library.search("2100").map(\.id) == [second.id])
    #expect(library.search("2200").isEmpty)
}

@Test func draftToggleEmptyCorrectionAndDiscardPreserveReviewSemantics() {
    var library = SessionLibrary()
    let record = Record(observation: .init(text: "Synthetic train"))
    library.add(record)
    #expect(library.draft(for: record.id) == .init(text: "Synthetic train"))
    library.updateDraft(.init(text: "", usesCorrection: true), for: record.id)
    #expect(!library.canApproveDraft(for: record.id))
    let blockedApproval = library.approveDraft(for: record.id)
    #expect(!blockedApproval)
    #expect(library.records[0].reviewState == .pending)
    #expect(library.draft(for: record.id) == .init(text: "", usesCorrection: true))
    #expect(library.search("train").isEmpty)
    library.discard(record.id)
    // Reusing the synthetic ID verifies discarded draft state cannot reappear.
    library.add(record)
    #expect(library.draft(for: record.id) == .init(text: "Synthetic train"))
    library.updateDraft(.init(text: "Synthetic edited", usesCorrection: false), for: record.id)
    var draft = library.draft(for: record.id)!
    draft.usesCorrection = true
    library.updateDraft(draft, for: record.id)
    #expect(library.draft(for: record.id)?.text == "Synthetic edited")
    library.discard(record.id)
    library.updateDraft(draft, for: record.id)
    library.approveDraft(for: record.id)
    #expect(library.records.isEmpty)
    #expect(library.draft(for: record.id) == nil)
}

@Test func blankApprovalRetainsSourceAndAllowsManualCorrection() {
    var library = SessionLibrary()
    let record = Record(observation: .init(text: " \n\t"))
    library.add(record, sourceFingerprint: "synthetic-blank")
    #expect(!library.canApproveDraft(for: record.id))
    let blockedApproval = library.approveDraft(for: record.id)
    #expect(!blockedApproval)
    let blockedReview = library.review(record.id, correction: .init(text: " \n"))
    #expect(!blockedReview)
    #expect(library.pending.count == 1)
    #expect(library.record(forSourceFingerprint: "synthetic-blank")?.id == record.id)
    #expect(library.records[0].observation == record.observation)
    library.updateDraft(.init(text: "SYNTHETIC MANUAL NOTE", usesCorrection: true), for: record.id)
    #expect(library.canApproveDraft(for: record.id))
    let correctedApproval = library.approveDraft(for: record.id)
    #expect(correctedApproval)
    #expect(library.search("manual").map(\.id) == [record.id])
    #expect(library.records[0].observation == record.observation)
}

@Test func explicitApprovedEditPreservesSearchUntilSaveAndCancelKeepsAcceptedText() {
    var library = SessionLibrary()
    let record = Record(observation: .init(text: "SYNTHETIC train 1900"))
    library.add(record, sourceFingerprint: "synthetic-approved-edit")
    library.review(record.id, correction: .init(text: "SYNTHETIC train 2000"))
    library.updateApprovedEdit(.init(text: "unauthorized implicit edit", usesCorrection: true), for: record.id)
    #expect(library.approvedEdit(for: record.id) == nil)
    library.beginApprovedEdit(for: record.id)
    #expect(library.approvedEdit(for: record.id)?.text == "SYNTHETIC train 2000")
    library.updateApprovedEdit(.init(text: "SYNTHETIC train 2100", usesCorrection: true), for: record.id)
    library.add(Record(observation: .init(text: "SYNTHETIC other source")))
    #expect(library.search("2000").map(\.id) == [record.id])
    #expect(library.search("2100").isEmpty)
    library.cancelApprovedEdit(for: record.id)
    #expect(library.approvedEdit(for: record.id) == nil)
    #expect(library.search("2000").map(\.id) == [record.id])
    library.beginApprovedEdit(for: record.id)
    library.updateApprovedEdit(.init(text: " \n", usesCorrection: true), for: record.id)
    let blankSave = library.saveApprovedEdit(for: record.id)
    #expect(!blankSave)
    #expect(library.approvedEdit(for: record.id)?.text == " \n")
    #expect(library.search("2000").map(\.id) == [record.id])
    library.updateApprovedEdit(.init(text: "SYNTHETIC train 2200", usesCorrection: true), for: record.id)
    let saved = library.saveApprovedEdit(for: record.id)
    #expect(saved)
    #expect(library.search("2000").isEmpty)
    #expect(library.search("2200").map(\.id) == [record.id])
    #expect(library.records[0].observation == record.observation)
    #expect(library.record(forSourceFingerprint: "synthetic-approved-edit")?.id == record.id)
    #expect(library.approvedEdit(for: record.id) == nil)
    library.beginApprovedEdit(for: record.id)
    library.updateApprovedEdit(.init(text: "ignored draft", usesCorrection: false), for: record.id)
    let restoredOriginal = library.saveApprovedEdit(for: record.id)
    #expect(restoredOriginal)
    #expect(library.search("1900").map(\.id) == [record.id])
    #expect(library.records[0].correction == nil)
    library.beginApprovedEdit(for: record.id)
    library.discard(record.id)
    #expect(library.approvedEdit(for: record.id) == nil)
    #expect(library.record(forSourceFingerprint: "synthetic-approved-edit") == nil)
    #expect(library.search("1900").isEmpty)
}
